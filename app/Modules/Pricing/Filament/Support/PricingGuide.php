<?php

declare(strict_types=1);

namespace App\Modules\Pricing\Filament\Support;

use Filament\Schemas\Components\Callout;
use Illuminate\Support\HtmlString;

/**
 * Persian guide boxes that explain pricing where admins set it (roadmap D3.2, owner 2026-11-09): the SKU suppliers
 * page, the SKU form, and the commission fields of products and brands. Each has a worked example.
 */
final class PricingGuide
{
    public static function suppliers(): Callout
    {
        return self::callout('قیمت فروش این SKU چطور تعیین می‌شود', [
            '<strong>تأمین‌کننده فعال:</strong> سایت از ارزان‌ترین تأمین‌کننده‌ای می‌فروشد که «فروش از این تأمین‌کننده» روشن، «موجود نزد تأمین‌کننده» روشن و خود تأمین‌کننده فعال باشد. ردیف فعال با برچسب سبز «فعال» مشخص است.',
            '<strong>دو کلید هر ردیف:</strong> «موجود نزد تأمین‌کننده» یعنی تأمین‌کننده کالا را دارد (با اکسل قیمت هم به‌روز می‌شود). «فروش از این تأمین‌کننده» تصمیم شماست: خاموشش کنید تا از این تأمین‌کننده نفروشیم. با خاموش شدن تأمین‌کننده فعال، ارزان‌ترین تأمین‌کننده بعدی خودکار جای آن را می‌گیرد و قیمت سایت و جستجو چند ثانیه بعد به‌روز می‌شود.',
            '<strong>قیمت فروش:</strong> قیمت خرید تأمین‌کننده فعال × (۱ + کمیسیون)، گرد شده به بالا تا ۱٬۰۰۰ تومان، و هرگز بیشتر از قیمت روی جعبه. ستون «قیمت فروش با کمیسیون» نشان می‌دهد هر تأمین‌کننده اگر فعال باشد چه قیمتی می‌سازد.',
            '<strong>مثال:</strong> کمیسیون ۱۰٪. سینا ۸۵۰٬۰۰۰ (فروش خاموش)، البرز ۸۷۰٬۰۰۰، هجرت ۹۰۰٬۰۰۰ تومان ← تأمین‌کننده فعال البرز است و قیمت فروش ۹۵۷٬۰۰۰ تومان. اگر البرز ناموجود شود، هجرت فعال می‌شود و قیمت ۹۹۰٬۰۰۰ تومان.',
            '<strong>بدون تأمین‌کننده فعال:</strong> اگر SKU تأمین‌کننده‌ای ندارد یا هیچ‌کدام قابل فروش نیست (فروش خاموش، ناموجود یا تأمین‌کننده غیرفعال)، با <strong>قیمت روی جعبه</strong> فروخته می‌شود و موجود می‌ماند. فقط اگر قیمت روی جعبه هم نداشته باشد «ناموجود» می‌شود.',
            '<strong>مثال بدون تأمین‌کننده:</strong> روی جعبه ۱٬۰۰۰٬۰۰۰ تومان و همه تأمین‌کننده‌ها خاموش ← قیمت فروش ۱٬۰۰۰٬۰۰۰ تومان. با روشن شدن دوباره یکی از آن‌ها، قیمت دوباره از قیمت خرید و کمیسیون ساخته می‌شود.',
        ]);
    }

    public static function skuForm(): Callout
    {
        return self::callout('قیمت‌ها چطور کار می‌کنند', [
            '<strong>قیمت فروش را وارد نمی‌کنید:</strong> سیستم آن را از قیمت خرید تأمین‌کننده فعال و کمیسیون می‌سازد: قیمت خرید × (۱ + کمیسیون)، گرد شده به بالا تا ۱٬۰۰۰ تومان. تأمین‌کنندگان در صفحه «تأمین‌کنندگان» همین SKU تعریف می‌شوند.',
            '<strong>بدون تأمین‌کننده فعال:</strong> اگر SKU تأمین‌کننده ندارد یا هیچ تأمین‌کننده‌ای قابل فروش نیست، با قیمت روی جعبه فروخته می‌شود. بدون قیمت روی جعبه و بدون تأمین‌کننده فعال، «ناموجود» است.',
            '<strong>موجودی:</strong> خودکار است: با تأمین‌کننده فعال یا قیمت روی جعبه «موجود»، بدون هیچ‌کدام «ناموجود».',
            '<strong>کمیسیون:</strong> کمیسیون خود محصول؛ اگر خالی باشد، کمیسیون برند. بدون هیچ‌کدام، تنوع ذخیره نمی‌شود.',
            '<strong>قیمت روی جعبه:</strong> سقف قیمت است؛ اگر قیمت حساب‌شده بیشتر شود، همان قیمت روی جعبه فروخته می‌شود (سود کمتر از کمیسیون، در تاریخچه علامت می‌خورد). در سایت خط‌خورده نمایش داده می‌شود. برای دارو الزامی است.',
            '<strong>حراج:</strong> اختیاری و باید کمتر از قیمت فروش باشد؛ اگر با تغییر قیمت دیگر کمتر نباشد، خودکار حذف و در تاریخچه علامت‌گذاری می‌شود.',
            '<strong>مثال:</strong> قیمت خرید ۸۵۰٬۰۰۰، کمیسیون ۱۰٪، روی جعبه ۱٬۰۰۰٬۰۰۰ تومان ← قیمت فروش ۹۳۵٬۰۰۰ تومان. با حراج ۸۹۹٬۰۰۰ مشتری ۸۹۹٬۰۰۰ می‌پردازد.',
            '<strong>زمان:</strong> محاسبه در پس‌زمینه انجام می‌شود؛ قیمت جدید معمولاً چند ثانیه بعد از ذخیره در جدول و سایت دیده می‌شود.',
        ]);
    }

    public static function productCommission(): Callout
    {
        return self::callout('کمیسیون محصول', [
            'این درصد روی همه تنوع‌های (SKU) این محصول اعمال می‌شود و بر کمیسیون برند مقدم است. خالی بگذارید تا کمیسیون برند استفاده شود.',
            '<strong>مثال:</strong> برند ۱۰٪ و محصول ۱۲٪ ← قیمت فروش هر SKU = قیمت خرید × ۱٫۱۲. با پاک کردن ۱۲٪، دوباره ۱۰٪ برند اعمال می‌شود.',
            'با ذخیره، قیمت تنوع‌ها در پس‌زمینه دوباره محاسبه می‌شود و چند ثانیه بعد در سایت دیده می‌شود.',
        ]);
    }

    public static function brandCommission(): Callout
    {
        return self::callout('کمیسیون برند', [
            'این درصد برای همه محصولات این برند که کمیسیون اختصاصی ندارند به کار می‌رود. بدون کمیسیون برند یا محصول، تنوع این محصولات ذخیره نمی‌شود.',
            '<strong>مثال:</strong> کمیسیون ۱۰٪ و قیمت خرید ۵۰۰٬۰۰۰ تومان ← قیمت فروش ۵۵۰٬۰۰۰ تومان.',
            'با تغییر آن، قیمت همه این محصولات در پس‌زمینه دوباره محاسبه می‌شود.',
        ]);
    }

    public static function withoutSuppliers(): Callout
    {
        return self::callout('چرا این فهرست مهم است', [
            'این تنوع‌ها هنوز تأمین‌کننده ندارند، پس با <strong>قیمت روی جعبه</strong> فروخته می‌شوند (بدون قیمت روی جعبه «ناموجود» هستند) و سود آن‌ها با کمیسیون شما تنظیم نمی‌شود.',
            'برای هر کدام «تأمین‌کنندگان» را باز کنید و دست‌کم یک تأمین‌کننده با قیمت خرید اضافه کنید؛ از آن به بعد قیمت از قیمت خرید و کمیسیون ساخته می‌شود و تنوع از این فهرست بیرون می‌رود.',
        ]);
    }

    /**
     * @param  list<string>  $paragraphs  trusted HTML
     */
    private static function callout(string $title, array $paragraphs): Callout
    {
        $html = '';

        foreach ($paragraphs as $index => $paragraph) {
            $html .= '<p style="margin-top: '.($index === 0 ? '0' : '0.5rem').'">'.$paragraph.'</p>';
        }

        return Callout::make($title)->info()->description(new HtmlString($html));
    }
}
