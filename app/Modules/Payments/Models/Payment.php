<?php

declare(strict_types=1);

namespace App\Modules\Payments\Models;

use App\Modules\Payments\Enums\PaymentAttemptStatus;
use App\Modules\Payments\Enums\PaymentKind;
use App\Modules\Payments\Enums\RefundSource;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Carbon;

/**
 * One payment attempt for an order (roadmap D7.4, S23), the difference after staff edit a paid order, or a refund owed
 * to the customer (owner, 2026-11-19: kind). An order has at most one pending, unexpired attempt of each kind; its link
 * is reused until it ends. Refund approvals are written to the activity log by the actions. A record of the gateway exchange, so it is not in the admin audit log.
 */
final class Payment extends Model
{
    public const string COLUMN_ID = 'id';

    public const string COLUMN_ORDER_ID = 'order_id';

    /**
     * Generated by MySQL from status and order_id (never written): the order id while the attempt is paid, else null.
     * Its unique key allows one paid attempt per order (owner, 2026-11-15).
     */
    public const string COLUMN_PAID_ORDER_ID = 'paid_order_id';

    public const string COLUMN_GATEWAY = 'gateway';

    public const string COLUMN_AMOUNT = 'amount';

    public const string COLUMN_AUTHORITY = 'authority';

    public const string COLUMN_URL = 'url';

    public const string COLUMN_STATUS = 'status';

    public const string COLUMN_EXPIRES_AT = 'expires_at';

    public const string COLUMN_REF_ID = 'ref_id';

    public const string COLUMN_CARD_PAN = 'card_pan';

    public const string COLUMN_CARD_HASH = 'card_hash';

    public const string COLUMN_FEE_TYPE = 'fee_type';

    public const string COLUMN_FEE = 'fee';

    public const string COLUMN_FAILURE_REASON = 'failure_reason';

    public const string COLUMN_VERIFIED_AT = 'verified_at';

    public const string COLUMN_FAILED_AT = 'failed_at';

    public const string COLUMN_CREATED_AT = 'created_at';

    public const string COLUMN_KIND = 'kind';

    public const string COLUMN_REFUND_SOURCE = 'refund_source';

    public const string COLUMN_ORDER_RETURN_ID = 'order_return_id';

    public const string COLUMN_REASON = 'reason';

    public const string COLUMN_DETAILS = 'details';

    public const string COLUMN_CREATED_BY = 'created_by';

    public const string COLUMN_DECIDED_BY = 'decided_by';

    public const string COLUMN_DECIDED_AT = 'decided_at';

    /**
     * The gateway name of refund records, which never touch a gateway.
     */
    public const string MANUAL_GATEWAY = 'manual';

    public function getId(): int
    {
        return (int) $this->getAttribute(self::COLUMN_ID);
    }

    public function getOrderId(): int
    {
        return (int) $this->getAttribute(self::COLUMN_ORDER_ID);
    }

    public function setOrderId(int $orderId): static
    {
        return $this->setAttribute(self::COLUMN_ORDER_ID, $orderId);
    }

    /**
     * The order's own payment, the difference after an edit, or a refund owed (owner, 2026-11-19).
     */
    public function getKind(): PaymentKind
    {
        return $this->getAttribute(self::COLUMN_KIND) ?? PaymentKind::Order;
    }

    public function setKind(PaymentKind $kind): static
    {
        return $this->setAttribute(self::COLUMN_KIND, $kind);
    }

    public function getRefundSource(): ?RefundSource
    {
        return $this->getAttribute(self::COLUMN_REFUND_SOURCE);
    }

    public function setRefundSource(?RefundSource $source): static
    {
        return $this->setAttribute(self::COLUMN_REFUND_SOURCE, $source);
    }

    public function getOrderReturnId(): ?int
    {
        $value = $this->getAttribute(self::COLUMN_ORDER_RETURN_ID);

        return $value === null ? null : (int) $value;
    }

    public function setOrderReturnId(?int $orderReturnId): static
    {
        return $this->setAttribute(self::COLUMN_ORDER_RETURN_ID, $orderReturnId);
    }

    public function getReason(): ?string
    {
        $value = $this->getAttribute(self::COLUMN_REASON);

        return $value === null ? null : (string) $value;
    }

    public function setReason(?string $reason): static
    {
        return $this->setAttribute(self::COLUMN_REASON, $reason);
    }

    /**
     * A cancelled order's refund split: items and shipping (rial).
     *
     * @return array{items?: int, shipping?: int}
     */
    public function getDetails(): array
    {
        return $this->getAttribute(self::COLUMN_DETAILS) ?? [];
    }

    /**
     * @param  array{items?: int, shipping?: int}  $details
     */
    public function setDetails(array $details): static
    {
        return $this->setAttribute(self::COLUMN_DETAILS, $details === [] ? null : $details);
    }

    public function getCreatedBy(): ?int
    {
        $value = $this->getAttribute(self::COLUMN_CREATED_BY);

        return $value === null ? null : (int) $value;
    }

    public function setCreatedBy(?int $adminId): static
    {
        return $this->setAttribute(self::COLUMN_CREATED_BY, $adminId);
    }

    public function getDecidedBy(): ?int
    {
        $value = $this->getAttribute(self::COLUMN_DECIDED_BY);

        return $value === null ? null : (int) $value;
    }

    public function setDecidedBy(?int $adminId): static
    {
        return $this->setAttribute(self::COLUMN_DECIDED_BY, $adminId);
    }

    public function getDecidedAt(): ?Carbon
    {
        return $this->getAttribute(self::COLUMN_DECIDED_AT);
    }

    public function setDecidedAt(?Carbon $decidedAt): static
    {
        return $this->setAttribute(self::COLUMN_DECIDED_AT, $decidedAt);
    }

    /**
     * The status as staff read it: a refund is waiting for approval, paid back or rejected.
     */
    public function statusLabel(): string
    {
        if ($this->getKind() !== PaymentKind::Refund) {
            return $this->getStatus()->label();
        }

        return match ($this->getStatus()) {
            PaymentAttemptStatus::Pending => 'در انتظار تأیید',
            PaymentAttemptStatus::Paid => 'بازگردانده شد',
            default => 'رد شد',
        };
    }

    public function getGateway(): string
    {
        return (string) $this->getAttribute(self::COLUMN_GATEWAY);
    }

    public function setGateway(string $gateway): static
    {
        return $this->setAttribute(self::COLUMN_GATEWAY, $gateway);
    }

    public function getAmount(): int
    {
        return (int) $this->getAttribute(self::COLUMN_AMOUNT);
    }

    public function setAmount(int $amount): static
    {
        return $this->setAttribute(self::COLUMN_AMOUNT, $amount);
    }

    public function getAuthority(): string
    {
        return (string) $this->getAttribute(self::COLUMN_AUTHORITY);
    }

    public function setAuthority(string $authority): static
    {
        return $this->setAttribute(self::COLUMN_AUTHORITY, $authority);
    }

    public function getUrl(): string
    {
        return (string) $this->getAttribute(self::COLUMN_URL);
    }

    public function setUrl(string $url): static
    {
        return $this->setAttribute(self::COLUMN_URL, $url);
    }

    public function getStatus(): PaymentAttemptStatus
    {
        return $this->getAttribute(self::COLUMN_STATUS);
    }

    public function setStatus(PaymentAttemptStatus $status): static
    {
        return $this->setAttribute(self::COLUMN_STATUS, $status);
    }

    public function getExpiresAt(): Carbon
    {
        return $this->getAttribute(self::COLUMN_EXPIRES_AT);
    }

    public function setExpiresAt(Carbon $expiresAt): static
    {
        return $this->setAttribute(self::COLUMN_EXPIRES_AT, $expiresAt);
    }

    public function getRefId(): ?string
    {
        $value = $this->getAttribute(self::COLUMN_REF_ID);

        return $value === null ? null : (string) $value;
    }

    public function setRefId(?string $refId): static
    {
        return $this->setAttribute(self::COLUMN_REF_ID, $refId);
    }

    public function getCardPan(): ?string
    {
        return $this->getAttribute(self::COLUMN_CARD_PAN);
    }

    public function setCardPan(?string $cardPan): static
    {
        return $this->setAttribute(self::COLUMN_CARD_PAN, $cardPan);
    }

    public function getCardHash(): ?string
    {
        return $this->getAttribute(self::COLUMN_CARD_HASH);
    }

    public function setCardHash(?string $cardHash): static
    {
        return $this->setAttribute(self::COLUMN_CARD_HASH, $cardHash);
    }

    public function getFeeType(): ?string
    {
        return $this->getAttribute(self::COLUMN_FEE_TYPE);
    }

    public function setFeeType(?string $feeType): static
    {
        return $this->setAttribute(self::COLUMN_FEE_TYPE, $feeType);
    }

    /**
     * Zarinpal's fee for this payment (rial), when it reported one.
     */
    public function getFee(): ?int
    {
        $fee = $this->getAttribute(self::COLUMN_FEE);

        return $fee === null ? null : (int) $fee;
    }

    public function setFee(?int $fee): static
    {
        return $this->setAttribute(self::COLUMN_FEE, $fee);
    }

    public function getFailureReason(): ?string
    {
        $value = $this->getAttribute(self::COLUMN_FAILURE_REASON);

        return $value === null ? null : (string) $value;
    }

    public function setFailureReason(?string $failureReason): static
    {
        return $this->setAttribute(self::COLUMN_FAILURE_REASON, $failureReason);
    }

    public function setVerifiedAt(?Carbon $verifiedAt): static
    {
        return $this->setAttribute(self::COLUMN_VERIFIED_AT, $verifiedAt);
    }

    public function setFailedAt(?Carbon $failedAt): static
    {
        return $this->setAttribute(self::COLUMN_FAILED_AT, $failedAt);
    }

    /**
     * Its link can still be used: pending and not expired.
     */
    public function isOpen(): bool
    {
        return $this->getStatus() === PaymentAttemptStatus::Pending && $this->getExpiresAt()->isFuture();
    }

    /**
     * @param  Builder<self>  $query
     * @return Builder<self>
     */
    public function scopeOpen(Builder $query): Builder
    {
        return $query->where(self::COLUMN_STATUS, PaymentAttemptStatus::Pending)->where(self::COLUMN_EXPIRES_AT, '>', now());
    }

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            self::COLUMN_STATUS => PaymentAttemptStatus::class,
            self::COLUMN_KIND => PaymentKind::class,
            self::COLUMN_REFUND_SOURCE => RefundSource::class,
            self::COLUMN_DECIDED_AT => 'datetime',
            self::COLUMN_DETAILS => 'array',
            self::COLUMN_AMOUNT => 'integer',
            self::COLUMN_EXPIRES_AT => 'datetime',
            self::COLUMN_VERIFIED_AT => 'datetime',
            self::COLUMN_FAILED_AT => 'datetime',
        ];
    }
}
