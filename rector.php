    ->withPaths([
        __DIR__.'/app',
        __DIR__.'/config',
        __DIR__.'/database',
        __DIR__.'/routes',
        __DIR__.'/tests',
    ])
    ->withPhpSets()
    ->withPreparedSets(
        deadCode: true,
        codeQuality: true,
        typeDeclarations: true,
    )
    ->withSkip([
        // Laravel passes the model to every policy method; the parameter documents which record is checked.
        RemoveUnusedPublicMethodParameterRector::class => [__DIR__.'/app/Modules/*/Policies/*'],
    ]);
